// Instruction is one row of the amd64 catalogue: one encoding form of one mnemonic.
//
// A row is a form rather than a mnemonic because that is the granularity a hand-encoder
// works at. VPSRLW has ten forms across VEX and EVEX at three widths and they do not share
// an opcode, so a table listing the mnemonic once would have to pick one - and picking is
// what the caller came to the table to do.
type Instruction struct {
	mnemonic string
	goknown  bool
	class    string
	spec     string
	intel    string
	gnu      string
	feature  string
}

// ArmInstruction is one row of the arm64 catalogue, again one encoding form.
//
// Every arm64 instruction is exactly one 32-bit word, so a row carries the finished base
// word: the fixed bits with every register and immediate field left zero. OR the operands
// into that and the result is the argument to WORD, which is the whole of what a macro
// needs.
type ArmInstruction struct {
	mnemonic string
	goname   string
	armname  string
	goknown  bool
	mask     uint32
	base     uint32
	fields   string
	variant  string
	syntax   string
}

// main resolves the two source trees, builds both catalogues and writes them out. A missing
// x/arch is not an error: the catalogue degrades to what the toolchain alone can say.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func main() {
	var (
		out  = flag.String("out", ".", "directory the catalogue is written to")
		arch = flag.String("arch", "", "path to a golang.org/x/arch tree; empty to skip")
		root = flag.String("goroot", "", "GOROOT to read the assembler tables from")
	)

	flag.Parse()
	log.SetFlags(0)
	log.SetPrefix("catalog: ")

	if *root == "" {
		*root = _Goroot()
	}

	if err := _Generate(*root, *arch, *out); err != nil {
		log.Fatal(err)
	}
}

// _Generate builds both catalogues and writes them into dir.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Generate(root, arch, dir string) error {
	amd64, err := _Amd64Catalog(root, arch)
	if err != nil {
		return fmt.Errorf("amd64 catalogue: %w", err)
	}

	arm64, err := _Arm64Catalog(root, arch)
	if err != nil {
		return fmt.Errorf("arm64 catalogue: %w", err)
	}

	if err := _WriteAmd64(filepath.Join(dir, "amd64.tsv"), amd64); err != nil {
		return err
	}

	if err := _WriteArm64(filepath.Join(dir, "arm64.tsv"), arm64); err != nil {
		return err
	}

	_Report("amd64", len(amd64), _CountMissing(amd64, func(i int) bool {
		return !amd64[i].goknown
	}))

	_Report("arm64", len(arm64), _CountMissing(arm64, func(i int) bool {
		return !arm64[i].goknown
	}))

	return nil
}

// _Amd64Catalog merges the three amd64 sources into one row set, one row per encoding form.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
//   - 2026-09-23 00:12: emits one row per encoding form rather than one per mnemonic, so a
//     mnemonic with several encodings no longer reports an arbitrary one of them
func _Amd64Catalog(root, arch string) ([]*Instruction, error) {
	names, err := _GoMnemonics(root, "x86")
	if err != nil {
		return nil, err
	}

	forms, err := _AvxForms(filepath.Join(root, "src/cmd/internal/obj/x86/avx_optabs.go"))
	if err != nil {
		return nil, err
	}

	intel, err := _IntelForms(arch)
	if err != nil {
		return nil, err
	}

	var (
		rows = make([]*Instruction, 0, len(names))
		seen = make(map[string]bool, len(names))
	)

	for _, name := range names {
		if seen[name] {
			continue
		}

		seen[name] = true
		rows = append(rows, _Amd64Rows(name, forms[name], intel[name])...)
	}

	for name, row := range intel {
		if !seen[name] {
			rows = append(rows, row)
		}
	}

	sort.Slice(rows, func(i, j int) bool {
		if rows[i].mnemonic != rows[j].mnemonic {
			return rows[i].mnemonic < rows[j].mnemonic
		}

		return rows[i].spec < rows[j].spec
	})

	return rows, nil
}

// _Amd64Rows expands one Go mnemonic into a row per encoding form.
//
// A mnemonic with no AVX form gets a single row carrying whatever the Intel table knows.
// Those are the legacy and SSE instructions, whose opcode map lives in asm6.go as operand
// tables rather than as the flat list avx_optabs.go keeps.
//
// Revisions:
//   - 2026-09-23 00:12: initial creation
func _Amd64Rows(name string, forms []string, intel *Instruction) []*Instruction {
	var (
		row = &Instruction{
			mnemonic: name,
			goknown:  true,
			class:    "legacy",
			spec:     ABSENT,
			intel:    ABSENT,
			gnu:      ABSENT,
			feature:  ABSENT,
		}
	)

	if intel != nil {
		row.spec = intel.spec
		row.intel = intel.intel
		row.gnu = intel.gnu
		row.feature = intel.feature
	}

	if len(forms) == 0 {
		return []*Instruction{row}
	}

	var (
		rows = make([]*Instruction, 0, len(forms))
	)

	for _, form := range forms {
		clone := *row
		clone.spec = form
		clone.class = _FormClass(form)
		rows = append(rows, &clone)
	}

	return rows
}

// _FormClass names the encoding one form uses.
//
// Revisions:
//   - 2026-09-23 00:12: initial creation
func _FormClass(form string) string {
	if strings.HasPrefix(form, "EVEX") {
		return "evex"
	}

	return "vex"
}

// _Mnemonics returns every mnemonic in a file's Anames table. The file is parsed as Go
// rather than scanned, and only that one declaration is read: obj/util.go holds the shared
// table beside ordinary code, so taking every string literal in the file would pull in
// error messages and flag names as though they were instructions.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
//   - 2026-09-22 22:58: reads the Anames declaration rather than every string literal, so
//     the shared pseudo-op table in obj/util.go can be read from the same function
func _Mnemonics(path string) ([]string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}

	var (
		names []string
	)

	ast.Inspect(file, func(node ast.Node) bool {
		spec, ok := node.(*ast.ValueSpec)
		if !ok || len(spec.Names) != 1 || spec.Names[0].Name != "Anames" {
			return true
		}

		names = append(names, _Strings(spec.Values)...)

		return false
	})

	if len(names) == 0 {
		return nil, fmt.Errorf("no Anames table in %s", path)
	}

	return names, nil
}

// _Strings collects the string literals of a slice literal. The first element of an
// architecture's table is keyed, to start numbering at A_ARCHSPECIFIC, so a keyed element
// counts the same as a bare one.
//
// Revisions:
//   - 2026-09-22 22:58: initial creation
func _Strings(values []ast.Expr) []string {
	var (
		names []string
	)

	for _, value := range values {
		lit, ok := value.(*ast.CompositeLit)
		if !ok {
			continue
		}

		for _, item := range lit.Elts {
			if pair, keyed := item.(*ast.KeyValueExpr); keyed {
				item = pair.Value
			}

			basic, ok := item.(*ast.BasicLit)
			if !ok || basic.Kind != token.STRING {
				continue
			}

			text, err := strconv.Unquote(basic.Value)
			if err != nil {
				continue
			}

			names = append(names, text)
		}
	}

	return names
}

// _GoMnemonics returns every mnemonic the assembler for one architecture accepts: the
// architecture's own table, and the pseudo-ops obj shares across all of them.
//
// The shared table is why this is not one file. CALL, JMP, RET and NOP are not in any
// architecture's anames.go, because every architecture has them; reading only the
// architecture file reports the four most common instructions in any kernel as unsupported.
//
// Revisions:
//   - 2026-09-22 22:58: initial creation
func _GoMnemonics(root, arch string) ([]string, error) {
	var (
		base = filepath.Join(root, "src/cmd/internal/obj")
	)

	names, err := _Mnemonics(filepath.Join(base, arch, "anames.go"))
	if err != nil {
		return nil, err
	}

	shared, err := _Mnemonics(filepath.Join(base, "util.go"))
	if err != nil {
		return nil, err
	}

	return append(names, shared...), nil
}

// _AvxForms reads avx_optabs.go and returns, per mnemonic, every encoding form it lists in
// Intel notation.
//
// The table is a flat opBytes list per instruction, with no delimiter between one form and
// the next. What separates them is that a form always opens with an expression naming
// avxEscape; everything after it up to the next such expression belongs to that form. An
// EVEX form carries one extra element after the flags - its tuple and masking argument -
// which is dropped here, because the catalogue records how an instruction is spelled, not
// how its operands are checked.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _AvxForms(path string) (map[string][]string, error) {
	var (
		set  = token.NewFileSet()
		file *ast.File
		err  error
	)

	file, err = parser.ParseFile(set, path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}

	var (
		forms = make(map[string][]string)
	)

	ast.Inspect(file, func(node ast.Node) bool {
		lit, ok := node.(*ast.CompositeLit)
		if !ok {
			return true
		}

		name, bytes := _OptabEntry(set, lit)
		if name == "" {
			return true
		}

		forms[name] = _SplitForms(set, bytes)

		return true
	})

	if len(forms) == 0 {
		return nil, fmt.Errorf("no AVX forms in %s", path)
	}

	return forms, nil
}

// _OptabEntry recognises one `{as: AVPSRLW, ..., op: opBytes{...}}` element and returns the
// mnemonic it names along with the opcode list. A composite literal that is not such an
// entry yields an empty name.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _OptabEntry(set *token.FileSet, lit *ast.CompositeLit) (string, []ast.Expr) {
	var (
		name  string
		bytes []ast.Expr
	)

	for _, item := range lit.Elts {
		pair, ok := item.(*ast.KeyValueExpr)
		if !ok {
			continue
		}

		key, ok := pair.Key.(*ast.Ident)
		if !ok {
			continue
		}

		switch key.Name {
		case "as":
			name = strings.TrimPrefix(_Render(set, pair.Value), "A")
		case "op":
			inner, ok := pair.Value.(*ast.CompositeLit)
			if ok {
				bytes = inner.Elts
			}
		}
	}

	if name == "" || len(bytes) == 0 {
		return "", nil
	}

	return name, bytes
}

// _SplitForms cuts a flat opBytes list into one Intel-notation string per encoding form.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _SplitForms(set *token.FileSet, bytes []ast.Expr) []string {
	var (
		forms   []string
		current []string
		evex    bool
	)

	flush := func() {
		if len(current) > 0 {
			forms = append(forms, strings.Join(current, " "))
		}
	}

	for _, item := range bytes {
		text := _Render(set, item)
		if !strings.Contains(text, "avxEscape") {
			if evex {
				evex = false

				continue
			}

			current = append(current, _OpcodeByte(text))

			continue
		}

		flush()

		evex = strings.Contains(text, "evex")
		current = []string{_VexSpec(text)}
	}

	flush()

	return forms
}

// _VexSpec turns a flag expression into Intel's notation, so "avxEscape | vex256 | vex66 |
// vex0F | vexW0" reads back as "VEX.256.66.0F.W0".
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _VexSpec(text string) string {
	var (
		parts = strings.Split(text, "|")
		found = make(map[string]string, len(VEX_ORDER))
		lead  = "VEX"
	)

	for _, part := range parts {
		flag := strings.TrimSpace(part)

		field, ok := VEX_FIELDS[flag]
		if !ok {
			continue
		}

		if strings.HasPrefix(flag, "evex") {
			lead = "EVEX"
		}

		found[VEX_GROUPS[field]] = field
	}

	var (
		spec = []string{lead}
	)

	for _, group := range VEX_ORDER {
		if value, ok := found[group]; ok {
			spec = append(spec, value)
		}
	}

	return strings.Join(spec, ".")
}

// _OpcodeByte normalises one opcode element to two hex digits. The table writes some of
// them in octal - 02 for a ModRM /2 extension - which Go reads as octal and a reader of the
// catalogue should not have to.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _OpcodeByte(text string) string {
	value, err := strconv.ParseUint(strings.TrimSpace(text), 0, 8)
	if err != nil {
		return strings.TrimSpace(text)
	}

	return fmt.Sprintf("%02X", value)
}

// _IntelForms reads x/arch's x86 CSV and returns one row per mnemonic. The CSV is the only
// source here that carries Intel and GNU spellings beside Go's, which is what lets a kernel
// written from the Intel manual, or ported from C intrinsics, be looked up by the name it
// had there.
//
// It stops at AVX2: the table is built from the December 2015 manual, so no AVX512 form is
// in it. Go's own avx_optabs.go covers those and is applied first, so the gap costs the
// catalogue only the Intel spelling of instructions Go already supports.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _IntelForms(arch string) (map[string]*Instruction, error) {
	if arch == "" {
		return nil, nil
	}

	handle, err := os.Open(filepath.Join(arch, "x86/x86.v0.2.csv"))
	if err != nil {
		return nil, fmt.Errorf("open x86 csv: %w", err)
	}

	defer func() {
		_ = handle.Close()
	}()

	var (
		reader = csv.NewReader(handle)
	)

	reader.Comment = '#'
	reader.FieldsPerRecord = -1

	records, err := reader.ReadAll()
	if err != nil {
		return nil, fmt.Errorf("read x86 csv: %w", err)
	}

	return _IntelRows(records), nil
}

// _IntelRows folds the CSV's operand forms down to one row per mnemonic. The first form
// wins, because the forms of one instruction differ in operand width rather than in how the
// instruction is named, and the catalogue is a name index.
//
// One CSV row can name several Go spellings, because Go distinguishes operand width by
// mnemonic where Intel distinguishes it by operand: PUSH is written "-/PUSHL/PUSHQ", the
// dash standing for a width 64-bit mode does not have. A row also marks a mnemonic the
// assembler accepts but never prints with a trailing star. Reading the column whole rather
// than splitting it is what made CALL, PUSH and most of CMOV look unsupported.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
//   - 2026-09-22 22:44: Go column split into its alternative spellings, so a row naming
//     more than one no longer reports every one of them missing
func _IntelRows(records [][]string) map[string]*Instruction {
	const (
		INTEL_COLUMN    = 0
		GO_COLUMN       = 1
		GNU_COLUMN      = 2
		ENCODING_COLUMN = 3
		FEATURE_COLUMN  = 6
		MINIMUM_COLUMNS = 7
	)

	var (
		rows = make(map[string]*Instruction, len(records))
	)

	for _, record := range records {
		if len(record) < MINIMUM_COLUMNS {
			continue
		}

		for _, name := range _GoSpellings(record[GO_COLUMN]) {
			if _, seen := rows[name]; seen {
				continue
			}

			rows[name] = &Instruction{
				mnemonic: name,
				goknown:  false,
				class:    "legacy",
				spec:     _Text(record[ENCODING_COLUMN]),
				intel:    _Head(record[INTEL_COLUMN]),
				gnu:      _Head(record[GNU_COLUMN]),
				feature:  _Text(record[FEATURE_COLUMN]),
			}
		}
	}

	return rows
}

// _GoSpellings returns every Go mnemonic the CSV's Go column names. A dash stands for a
// width the mode does not have and yields nothing.
//
// Revisions:
//   - 2026-09-22 22:44: initial creation
func _GoSpellings(column string) []string {
	var (
		names []string
	)

	for _, part := range strings.Split(_Head(column), "/") {
		name := strings.TrimSuffix(strings.TrimSpace(part), "*")
		if name == "" || name == ABSENT {
			continue
		}

		names = append(names, name)
	}

	return names
}

// _Arm64Catalog merges Go's arm64 mnemonics with x/arch's encoding table, one row per
// encoding form.
//
// One row per mnemonic was wrong here in a way that mattered: Go spells every load and
// store MOV, so MOVD alone stands for LDR and STR across three addressing modes, and a
// single row had to choose one and call it the encoding. The differential test caught it -
// MOVD (R1), R0 assembles to the unsigned-offset form and the table claimed post-index.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
//   - 2026-09-23 00:12: emits one row per encoding form, after the assembler check found
//     MOVD, MOVBU and ADD each carrying an arbitrary one of their several encodings
func _Arm64Catalog(root, arch string) ([]*ArmInstruction, error) {
	names, err := _GoMnemonics(root, "arm64")
	if err != nil {
		return nil, err
	}

	forms, err := _ArmForms(arch)
	if err != nil {
		return nil, err
	}

	var (
		known  = make(map[string]bool, len(names))
		filled = make(map[string]bool, len(names))
		rows   = make([]*ArmInstruction, 0, len(forms)+len(names))
	)

	for _, name := range names {
		known[name] = true
	}

	for _, form := range forms {
		name := _ArmSpelling(known, form.mnemonic, form.variant)
		if name != "" {
			form.goname = name
			form.goknown = true
			form.mnemonic = name
			filled[name] = true
		}

		rows = append(rows, form)
	}

	for _, name := range names {
		if filled[name] {
			continue
		}

		rows = append(rows, _BareArmRow(name))
	}

	sort.Slice(rows, func(i, j int) bool {
		if rows[i].mnemonic != rows[j].mnemonic {
			return rows[i].mnemonic < rows[j].mnemonic
		}

		return rows[i].syntax < rows[j].syntax
	})

	return rows, nil
}

// _BareArmRow is a mnemonic Go accepts that no encoding form matched. It is kept in the
// table rather than dropped, because "Go has this and the catalogue has no bytes for it" is
// a different answer from "this does not exist", and a caller looking a mnemonic up needs
// to be able to tell them apart.
//
// Revisions:
//   - 2026-09-23 00:12: initial creation
func _BareArmRow(name string) *ArmInstruction {
	return &ArmInstruction{
		mnemonic: name,
		goname:   name,
		armname:  ABSENT,
		goknown:  true,
		mask:     0,
		base:     0,
		fields:   ABSENT,
		variant:  ABSENT,
		syntax:   ABSENT,
	}
}

// _ArmSpelling returns the Go mnemonic that assembles an ARM instruction, or an empty
// string when none of the rules finds one.
//
// Go does not use ARM's names. cmd/internal/obj/arm64/doc.go sets out why: operand width
// moves from the operands into the mnemonic (FADD becomes FADDS or FADDD), most vector and
// floating-point instructions gain a V, conditions move into the opcode (B.EQ becomes BEQ),
// and every load and store is spelled MOV. The mechanical rules are applied here; the rest
// are a short table, because they are renamings rather than transformations.
//
// What this cannot do is prove a negative. An empty result means no rule found a spelling,
// which is an upper bound on what is really missing, not a measurement of it.
//
// Revisions:
//   - 2026-09-22 23:09: initial creation
func _ArmSpelling(known map[string]bool, name, variant string) string {
	var (
		table = ARM_RENAMED
	)

	if strings.Contains(variant, SIMD_TITLE) {
		table = ARM_RENAMED_SIMD
	}

	if renamed, ok := _Renamed(table[name], variant); ok {
		name = renamed
	}

	for _, candidate := range _ArmCandidates(name, variant) {
		if known[candidate] {
			return candidate
		}
	}

	return ""
}

// _Renamed picks a rename for one variant, preferring the entry that names its width.
//
// Revisions:
//   - 2026-09-23 00:58: initial creation
func _Renamed(widths map[string]string, variant string) (string, bool) {
	for width, name := range widths {
		if width != "" && strings.Contains(variant, width) {
			return name, true
		}
	}

	name, ok := widths[""]

	return name, ok
}

// _ArmCandidates returns the Go mnemonics that could spell one ARM encoding variant, most
// likely first.
//
// The variant is the only thing separating two encodings of the same ARM mnemonic, and it
// is what Go's prefix and suffix spell. FADD has a scalar single-precision form, a scalar
// double-precision one and a vector one; Go calls the first two FADDS and FADDD and does
// not support the third at all. A candidate list that ignored the variant would hand the
// vector encoding to FADDS, leave the scalar form with none, and report a gap that exists
// as though it were covered - the one failure mode that makes the table worse than nothing.
//
// Vector is therefore tested before precision, because "Vector single-precision and
// double-precision variant" names both and only the first word decides the spelling.
//
// Revisions:
//   - 2026-09-22 23:24: initial creation
//   - 2026-09-22 23:41: candidates driven by the variant rather than a fixed suffix order,
//     after the vector FADD encoding was found filed under scalar FADDS
func _ArmCandidates(name, variant string) []string {
	var (
		text = strings.ToLower(variant)
	)

	switch {
	case strings.Contains(variant, SIMD_TITLE):
		return []string{name + _Precision(text), "V" + name, name}
	case strings.Contains(text, "vector"), strings.Contains(text, "same type"):
		return []string{"V" + name, name}
	case strings.Contains(text, "half-precision"):
		return []string{name + "H"}
	case strings.Contains(text, "single-precision"):
		return []string{name + "S"}
	case strings.Contains(text, "double-precision"):
		return []string{name + "D"}
	case strings.Contains(text, "scalar"):
		return []string{name, name + "S", name + "D"}
	case strings.Contains(text, "32-bit"):
		return []string{name + "W", name}
	case strings.Contains(text, "64-bit"):
		return []string{name, name + "D"}
	default:
		return []string{name, "V" + name, name + "W", name + "S", name + "D"}
	}
}

// _Precision is the suffix Go puts on a floating-point mnemonic for one operand width. A
// width Go has no suffix for yields none, and the candidate is then filtered out by not
// being a mnemonic the assembler knows.
//
// Revisions:
//   - 2026-09-23 00:41: initial creation
func _Precision(variant string) string {
	switch {
	case strings.Contains(variant, "16-bit"), strings.Contains(variant, "half"):
		return "H"
	case strings.Contains(variant, "32-bit"), strings.Contains(variant, "single"):
		return "S"
	case strings.Contains(variant, "64-bit"), strings.Contains(variant, "double"):
		return "D"
	case strings.Contains(variant, "128-bit"):
		return "Q"
	default:
		return ""
	}
}

// _ArmForms reads x/arch's arm64 inst.json and returns one entry per encoding form.
//
// The mnemonic is taken from the head of the Syntax field, not from Name. Name is the
// title of the manual's section, so it reads "ADD (extended register)" or "ADDHN, ADDHN2",
// and matching on it would leave almost every base-set instruction looking unsupported.
// Syntax is the line the manual prints for that one encoding, and it opens with the
// mnemonic as it is actually written.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
//   - 2026-09-22 22:31: mnemonic read from Syntax rather than Name, which is a section
//     title and matched almost nothing
func _ArmForms(arch string) ([]*ArmInstruction, error) {
	if arch == "" {
		return nil, nil
	}

	raw, err := os.ReadFile(filepath.Join(arch, "arm64/arm64asm/inst.json"))
	if err != nil {
		return nil, fmt.Errorf("open arm64 table: %w", err)
	}

	var (
		table []struct {
			Name   string
			Bits   string
			Arch   string
			Syntax string
		}
	)

	if err := json.Unmarshal(raw, &table); err != nil {
		return nil, fmt.Errorf("parse arm64 table: %w", err)
	}

	var (
		forms = make([]*ArmInstruction, 0, len(table))
	)

	for _, entry := range table {
		mask, base, fields, err := _BitPattern(entry.Bits)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", entry.Name, err)
		}

		name := _Mnemonic(entry.Syntax, entry.Name)
		if name == "" {
			continue
		}

		forms = append(forms, &ArmInstruction{
			mnemonic: name,
			goname:   ABSENT,
			armname:  name,
			goknown:  false,
			mask:     mask,
			base:     base,
			fields:   fields,
			variant:  _Variant(entry.Name, entry.Arch),
			syntax:   _Text(entry.Syntax),
		})
	}

	return forms, nil
}

// _Variant renders the encoding variant, carrying over the one thing the section title says
// that the variant does not.
//
// ARM documents the integer and the floating-point load under the same mnemonic and tells
// them apart only in the title: "LDR (immediate)" against "LDR (immediate, SIMD&FP)". Both
// have a "64-bit variant", and Go calls the first MOVD and the second FMOVD. Without the
// title the two are indistinguishable, and every SIMD load ends up filed under MOVD - which
// is not a missing row but a wrong one, the failure a reader has no way to catch.
//
// Revisions:
//   - 2026-09-23 00:41: initial creation
func _Variant(title, variant string) string {
	if !strings.Contains(title, SIMD_TITLE) {
		return _Text(variant)
	}

	return SIMD_TITLE + " " + _Text(variant)
}

// _BitPattern turns an inst.json bit string into the mask of fixed bits, the value those
// bits take, and the operand fields left over.
//
// The value is the base word: every fixed bit set as the instruction requires and every
// register or immediate field zero. OR the operands into it and the result is a complete
// instruction word, which is what a WORD macro emits.
//
// The notation has five shapes, all of them present in the table: a single literal bit, a
// run of literal bits with an explicit width, a named field with a width, a one-bit named
// field, and a parenthesised run that ARM documents as "should be" a fixed value. The last
// is treated as fixed, because an encoder that left it clear would emit something the
// manual does not describe.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _BitPattern(bits string) (uint32, uint32, string, error) {
	var (
		mask   uint32
		base   uint32
		fields []string
		width  int
	)

	for _, item := range strings.Split(bits, "|") {
		var (
			text = strings.TrimSpace(item)
		)

		literal, name, size, err := _BitField(text)
		if err != nil {
			return 0, 0, "", err
		}

		width += size

		if name != "" {
			fields = append(fields, fmt.Sprintf("%s:%d", name, size))
			mask = mask << size
			base = base << size

			continue
		}

		for _, bit := range literal {
			mask = mask<<1 | 1
			base = base << 1

			if bit == '1' {
				base |= 1
			}
		}
	}

	if width != WORD_BITS {
		return 0, 0, "", fmt.Errorf("pattern is %d bits, want %d", width, WORD_BITS)
	}

	return mask, base, _Join(fields), nil
}

// _BitField classifies one element of a bit pattern. It returns the literal bits if the
// element is fixed, or the field name and its width if it is an operand.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _BitField(text string) (string, string, int, error) {
	var (
		fixed  = regexp.MustCompile(`^\(?([01]+)\)?$`)
		sized  = regexp.MustCompile(`^\(?(\w+)\)?:(\d+)$`)
		single = regexp.MustCompile(`^\w+$`)
	)

	if match := fixed.FindStringSubmatch(text); match != nil {
		return match[1], "", len(match[1]), nil
	}

	if match := sized.FindStringSubmatch(text); match != nil {
		size, err := strconv.Atoi(match[2])
		if err != nil {
			return "", "", 0, fmt.Errorf("width of %q: %w", text, err)
		}

		if literal := strings.Trim(match[1], "01"); literal == "" {
			return _Pad(match[1], size), "", size, nil
		}

		return "", match[1], size, nil
	}

	if single.MatchString(text) {
		return "", text, 1, nil
	}

	return "", "", 0, fmt.Errorf("unrecognised bit field %q", text)
}

// _Pad left-extends a literal run with zeros to the width the table declares for it. The
// table writes 0000:4 and also 00:4, so the digits alone do not always give the width.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Pad(literal string, size int) string {
	if len(literal) >= size {
		return literal[:size]
	}

	return strings.Repeat("0", size-len(literal)) + literal
}

// _WriteAmd64 writes the amd64 catalogue.
