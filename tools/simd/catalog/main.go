// _Goroot returns the toolchain root the tables are read from. It asks the go command
// rather than reading the environment, because GOROOT is normally unset and the answer
// then depends on which go is first on PATH - which is the whole point when a repository
// pins its own toolchain.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Goroot() string {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatalf("locate GOROOT: %v", err)
	}

	return strings.TrimSpace(string(out))
}

// _CountMissing counts the rows a predicate selects.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _CountMissing[T any](rows []T, missing func(int) bool) int {
	var (
		count int
	)

	for idx := range rows {
		if missing(idx) {
			count++
		}
	}

	return count
}

