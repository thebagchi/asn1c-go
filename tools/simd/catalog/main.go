// Command catalog builds the instruction catalogue that asmkit's macro layer is written
// against: for each architecture, every mnemonic Go's assembler accepts, the encoding it
// assembles to, and - where a wider table knows one - the instruction Go has no mnemonic
// for at all.
//
// That last set is why the tool exists. An instruction Go cannot spell is still reachable
// from a .s file as raw encoding bytes, BYTE on amd64 and WORD on arm64, and a #define is
// how it gets a name back. The catalogue says which instructions need that treatment and
// what bytes to emit for them.
//
// Sources, in order of authority:
//
//   - $GOROOT/src/cmd/internal/obj/{x86,arm64}/anames.go - what Go's assembler accepts.
//     Definitive, and it ships with the toolchain, so it never drifts from it.
//   - $GOROOT/src/cmd/internal/obj/x86/avx_optabs.go - the VEX and EVEX encoding of every
//     AVX form Go knows, AVX512 included.
//   - golang.org/x/arch - Intel and GNU spellings, CPUID features, and the ARM bit
//     patterns. Optional: without it the catalogue still lists everything Go supports, it
//     just cannot name what is missing or give an ARM base word.
//
// x/arch is read as data files, not imported, so this module gains no dependency from it.
// Point -arch at a checkout or at the module cache; the Makefile target downloads it.
//
// Usage:
//
//	go run tools/simd/catalog/main.go -out tools/simd/catalog
package main

