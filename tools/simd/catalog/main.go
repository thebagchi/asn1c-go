// _Mnemonic returns the instruction a syntax line names, falling back to the section title
// when the line is empty.
//
// The dot in "B.<cond>" is kept. Folding it away would make the conditional branch and the
// unconditional one the same instruction, and they are not: B is 0x14000000 and B.cond is
// 0x54000000. Go spells the conditional family BEQ, BNE and so on, so it has no single
// mnemonic to fold to either.
//
// Revisions:
//   - 2026-09-22 22:31: initial creation
//   - 2026-09-22 23:24: keeps the condition suffix, which had been merging the conditional
//     branch encoding into the row for the unconditional one
func _Mnemonic(syntax, title string) string {
	name := _Head(syntax)
	if name == "" {
		name = _Head(title)
	}

	return strings.Trim(name, ",")
}

// _Head returns the mnemonic at the start of a syntax string.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Head(text string) string {
	name, _, _ := strings.Cut(strings.TrimSpace(text), " ")

	return name
}

// _Text collapses an empty field to the absent marker, so a column is never blank and a
// tab-separated reader never sees two separators in a row.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Text(text string) string {
	trimmed := strings.TrimSpace(text)
	if trimmed == "" {
		return ABSENT
	}

	return strings.ReplaceAll(trimmed, SEPARATOR, " ")
}

// _Join renders a field list, or the absent marker when there is none.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Join(fields []string) string {
	if len(fields) == 0 {
		return ABSENT
	}

	return strings.Join(fields, ",")
}

// _Yes renders a boolean as the column's two spellings.
//
// Revisions:
//   - 2026-09-22 22:07: initial creation
func _Yes(value bool) string {
	if value {
		return "yes"
	}

	return "no"
}

