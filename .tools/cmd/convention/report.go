package main

import (
	"go/token"
	"strings"

	"golang.org/x/tools/go/analysis"
)

// LEVEL_ERROR is the level for a broken rule.
const (
	LEVEL_ERROR   = "error"
	LEVEL_WARNING = "warning"
	LEVEL_LOG     = "log"
)

// FIX_HISTORY is the edit for a missing revision history.
const (
	FIX_HISTORY     = "add a Revisions list whose first bullet is initial creation"
	FIX_INITIAL     = "change the first Revisions bullet so it contains initial creation"
	FIX_TIME        = "write the local time to the minute"
	FIX_INDENT      = "write the comment space, two spaces, and then - before the entry"
	FIX_FIELDS      = "delete the blank line or the comment between the fields"
	FIX_BODY        = "put each statement on its own line between the braces"
	FIX_DEFER       = "open the body after the brace and close it on its own line"
	FIX_GUARD       = "move the lock to the line above the first field it guards"
	FIX_DECLARE     = "write a var block"
	FIX_BANNER      = "put // Code generated by <tool>. DO NOT EDIT. on line 1"
	FIX_LEAD        = "give the name a leading _ and a capital letter"
	FIX_SNAKE       = "spell the name in CAPITAL_SNAKE"
	FIX_OPEN        = "put the first field on the line after the brace"
	FIX_SHARED      = "put one field on each line"
	FIX_CLOSE       = "put the closing brace on its own line"
	FIX_CALL_OPEN   = "put the first argument on the line after the parenthesis"
	FIX_CALL_SHARED = "put one argument on each line"
	FIX_CALL_CLOSE  = "put the closing parenthesis on its own line"
	FIX_SIGN_OPEN   = "put the first parameter on the line after the parenthesis"
	FIX_SIGN_SHARED = "put one parameter on each line"
	FIX_SIGN_CLOSE  = "put the closing parenthesis on its own line"
)

// Line builds one line an agent can read.
// The level is error, warning, or log.
// An empty fix omits the fix clause.
//
// Revisions:
//   - 2026-10-04 01:38: initial creation
func Line(
	level string,
	rule string,
	message string,
	fix string,
) string {
	text := level + ": " + rule + ": " + message
	if fix == "" {
		return text
	}

	return text + ". fix: " + fix
}

// Count reports one error or one warning for a finding line.
// A log line counts as neither.
// A warning must not fail the gate.
//
// Revisions:
//   - 2026-10-04 01:38: initial creation
func Count(text string) (int, int) {
	switch {
	case strings.HasPrefix(
		text,
		LEVEL_WARNING+":",
	):
		return 0, 1
	case strings.HasPrefix(
		text,
		LEVEL_LOG+":",
	):
		return 0, 0
	default:
		return 1, 0
	}
}

// _Fail reports one broken rule and the edit that repairs it.
//
// Revisions:
//   - 2026-10-04 01:38: initial creation
func _Fail(
	pass *analysis.Pass,
	pos token.Pos,
	message string,
	fix string,
) {
	pass.Reportf(
		pos,
		"%s",
		Line(
			LEVEL_ERROR,
			pass.Analyzer.Name,
			message,
			fix,
		),
	)
}
